public class StudentGrade {
    public static void main(String[] args) {
        // Example student grade
        int score = 85;
        
        if (score >= 80) {
            System.out.println("Grade: A");
        } else if (score >= 70) {
            System.out.println("Grade: B");
        } else {
            System.out.println("Grade: C");
        }
    }
}